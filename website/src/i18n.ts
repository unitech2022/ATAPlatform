export const dictionary: Record<Lang, Record<TranslationKey, string>> = { ar, en }

export type TranslationParams = Record<string, string | number>

export function translate(lang: Lang, key: TranslationKey, params?: TranslationParams): string {
  const template = dictionary[lang][key]
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name]
    return value === undefined ? match : String(value)
  })
}

export function readStoredLanguage(): Lang {
  try {
    const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY)
    return stored === 'en' ? 'en' : 'ar'
  } catch {
    return 'ar'
  }
}

export function directionOf(lang: Lang): 'rtl' | 'ltr' {
  return lang === 'ar' ? 'rtl' : 'ltr'
}

export interface I18nContextValue {
  lang: Lang
  dir: 'rtl' | 'ltr'
  setLang: (lang: Lang) => void
  t: (key: TranslationKey, params?: TranslationParams) => string
}

export const I18nContext = createContext<I18nContextValue>({
  lang: 'ar',
  dir: 'rtl',
  setLang: () => {},
  t: (key, params) => translate('ar', key, params),
})

export function useI18n(): I18nContextValue {
  return useContext(I18nContext)
}
